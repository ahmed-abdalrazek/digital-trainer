SUPPORTED_OPS = {"title", "text", "box", "arrow", "polygon", "line", "circle", "curve", "callout", "graph", "dot", "erase", "clear"}


def normalize_state(state=None):
    state = state if isinstance(state, dict) else {}
    try:
        index = int(state.get("index", 0))
    except (TypeError, ValueError):
        index = 0
    return {
        "index": max(0, min(index, len(SECTIONS))),
        "approved": state.get("approved", []) if isinstance(state.get("approved", []), list) else [],
        "edits": state.get("edits", {}) if isinstance(state.get("edits", {}), dict) else {},
        "published": bool(state.get("published", False)),
    }


def review_section(state, explanation, board_json, approve):
    """Return updated browser state and feedback; never generates lesson content."""
    state = normalize_state(state)
    index = state["index"]
    if index >= len(SECTIONS):
        return state, "اكتملت مراجعة جميع الأجزاء في المثال.", "", "[]", True
    section = SECTIONS[index]
    if not approve:
        return state, f"⏸️ بقيت عند **{section['title']}**. عدّل الشرح أو الرسم ثم اعتمده للانتقال.", explanation, board_json, False
    try:
        operations = json.loads(board_json or "[]")
        if not isinstance(operations, list) or any(not isinstance(op, dict) or op.get("op") not in SUPPORTED_OPS for op in operations):
            raise ValueError("unsupported operations")
        if not str(explanation or "").strip():
            raise ValueError("empty explanation")
    except (json.JSONDecodeError, ValueError):
        return state, "⚠️ لم يُعتمد الجزء: أضف شرحًا وتأكد أن الرسم JSON صحيح ويستخدم عمليات السبورة المدعومة.", explanation, board_json, False
    state["edits"][str(index)] = {"explanation": explanation.strip(), "board": operations}
    if index not in state["approved"]:
        state["approved"].append(index)
    state["index"] = index + 1
    if state["index"] >= len(SECTIONS):
        return state, f"✅ اعتُمدت الأجزاء {len(SECTIONS)}. راجع المثال ثم فعّل النشر من الزر أدناه.", "", "[]", True
    next_section = SECTIONS[state["index"]]
    return state, (f"✅ تم اعتماد **{section['title']}**.\n\n"
                   f"التالي للمراجعة: **{next_section['title']}** — {next_section['objective']}"), \
        next_section["explanation"], next_section["board"], False


def publish(state):
    state = normalize_state(state)
    if state["index"] != len(SECTIONS) or state["approved"] != list(range(len(SECTIONS))):
        return state, "لا يمكن النشر قبل اعتماد جميع الأجزاء."
    state["published"] = True
    return state, f"✅ نُشرت محاضرة {LESSON_TITLE} في نموذج العرض."
